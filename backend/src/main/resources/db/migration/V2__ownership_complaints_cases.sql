-- v1.2: ownership history (FR-13), public complaints (FR-14) and cases (FR-15).
-- Drivers are no longer linked to rickshaws; the assignment table is kept for history but no longer used.
-- Portable SQL: runs on PostgreSQL and on H2 in PostgreSQL mode.

-- "One open ownership per rickshaw" is enforced in OwnershipService (partial unique indexes are not portable).
create table ownership (
    id          bigint generated by default as identity primary key,
    rickshaw_id bigint not null references rickshaw (id),
    owner_id    bigint not null references owner (id),
    from_date   timestamp with time zone not null,
    to_date     timestamp with time zone,
    changed_by  bigint not null references app_user (id),
    note        varchar(500)
);
create index idx_ownership_rickshaw on ownership (rickshaw_id, to_date);

insert into ownership (rickshaw_id, owner_id, from_date, changed_by)
select id, owner_id, registered_at, registered_by from rickshaw;

create sequence complaint_no_seq start with 1;
create sequence case_no_seq start with 1;

create table complaint (
    id                bigint generated by default as identity primary key,
    complaint_no      varchar(20)   not null unique,
    rickshaw_id       bigint        not null references rickshaw (id),
    driver_id         bigint        not null references driver (id),
    complainant_name  varchar(100)  not null,
    complainant_phone varchar(11)   not null,
    complainant_nid   varchar(17)   not null,
    category          varchar(30)   not null,
    description       varchar(2000) not null,
    incident_at       timestamp with time zone,
    thana             varchar(50),
    status            varchar(20)   not null,
    resolution_note   varchar(1000),
    handled_by        bigint references app_user (id),
    filed_at          timestamp with time zone not null,
    updated_at        timestamp with time zone not null
);
create index idx_complaint_rickshaw on complaint (rickshaw_id);
create index idx_complaint_driver on complaint (driver_id);
create index idx_complaint_status on complaint (status);
create index idx_complaint_filed_at on complaint (filed_at);

create table case_file (
    id              bigint generated by default as identity primary key,
    case_no         varchar(20)   not null unique,
    rickshaw_id     bigint references rickshaw (id),
    driver_id       bigint references driver (id),
    complaint_id    bigint references complaint (id),
    offence         varchar(200)  not null,
    description     varchar(2000) not null,
    incident_at     timestamp with time zone not null,
    thana           varchar(50)   not null,
    status          varchar(20)   not null,
    resolution_note varchar(1000),
    filed_by        bigint        not null references app_user (id),
    filed_at        timestamp with time zone not null,
    updated_at      timestamp with time zone not null,
    closed_at       timestamp with time zone
);
create index idx_case_rickshaw on case_file (rickshaw_id);
create index idx_case_driver on case_file (driver_id);
create index idx_case_complaint on case_file (complaint_id);
create index idx_case_status on case_file (status);
create index idx_case_filed_at on case_file (filed_at);

create table case_evidence (
    case_id  bigint not null references case_file (id),
    photo_id uuid   not null references photo (id),
    primary key (case_id, photo_id)
);
